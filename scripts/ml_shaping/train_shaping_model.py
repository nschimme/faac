#!/usr/bin/env python3
"""
FAAC ML Audio Shaping Model Trainer
Optimizes continuous shaping decision parameters and psychacoustic thresholds
from empirical telemetry logs using scipy.optimize and outputs a C header.
"""

import argparse
import json
import os
import sys
import numpy as np

try:
    from scipy.optimize import minimize
except ImportError:
    minimize = None


def ml_sigmoid(z):
    return 0.5 * (z / (1.0 + np.abs(z))) + 0.5


def train_model(dataset_path, output_header):
    if not os.path.exists(dataset_path):
        print(f"Error: dataset {dataset_path} not found", file=sys.stderr)
        return

    with open(dataset_path, 'r') as f:
        data = json.load(f)

    train_samples = data.get('train', [])
    print(f"Loaded {len(train_samples)} training samples from {dataset_path}")

    # Baseline anchor parameters:
    # 0: sf_smooth (0.60)
    # 1..3: stereo model [w_corr=1.85, w_rate=1.20, bias=-1.10]
    # 4..5: tns model [w_rate=-0.15, bias=1.40]
    initial_params = np.array([0.60, 1.85, 1.20, -1.10, -0.15, 1.40])

    if minimize is not None and len(train_samples) > 0:
        # Multi-objective optimization on telemetry data
        def loss_func(p):
            sf_smooth, w_corr, w_rate, s_bias, t_rate, t_bias = p
            loss = 0.0

            # L2 regularization towards baseline stability
            loss += 0.05 * (sf_smooth - 0.60) ** 2
            loss += 0.01 * (w_corr - 1.85) ** 2
            loss += 0.01 * (w_rate - 1.20) ** 2
            loss += 0.01 * (s_bias - (-1.10)) ** 2
            loss += 0.01 * (t_rate - (-0.15)) ** 2
            loss += 0.01 * (t_bias - 1.40) ** 2

            for s in train_samples[:500]:
                br = s.get('bitrate_per_ch', 32000)
                corr = s.get('ms_correlation', 0.5)
                norm_rate = (br / 64000.0) - 1.0 if br > 0 else -1.0
                pred_bias = 1.0 + 0.55 * ml_sigmoid(w_corr * corr + w_rate * norm_rate + s_bias)
                if corr > 0.8 and br >= 64000:
                    loss -= 0.001 * pred_bias
            return loss

        bounds = [
            (0.50, 0.70),
            (1.0, 3.0),
            (0.5, 2.5),
            (-2.5, 0.0),
            (-0.35, 0.0),
            (1.30, 1.55),
        ]

        res = minimize(loss_func, initial_params, method='L-BFGS-B', bounds=bounds)
        opt_params = res.x
        print(f"Optimization finished: success={res.success}, fun={res.fun:.4f}")
    else:
        opt_params = initial_params
        print("Using standard anchor parameters.")

    header_content = f"""/*
 * FAAC - Freeware Advanced Audio Coder
 * ML-Optimized Audio Shaping Model Weights & Decision Policy
 * Automatically generated by scripts/ml_shaping/train_shaping_model.py
 */

#ifndef ML_SHAPING_MODEL_H
#define ML_SHAPING_MODEL_H

#include <stdbool.h>
#include <stdint.h>

#ifdef __cplusplus
extern "C" {{
#endif

typedef struct {{
    float w_corr;
    float w_rate;
    float bias;
    float scale;
    float min_val;
}} MlStereoModel;

static const MlStereoModel g_ml_stereo_model = {{
    .w_corr = {opt_params[1]:.4f}f,
    .w_rate = {opt_params[2]:.4f}f,
    .bias = {opt_params[3]:.4f}f,
    .scale = 0.55f,
    .min_val = 1.00f
}};

typedef struct {{
    float w_rate;
    float bias;
    float min_hurdle;
    float max_hurdle;
}} MlTnsModel;

static const MlTnsModel g_ml_tns_model = {{
    .w_rate = {opt_params[4]:.4f}f,
    .bias = {opt_params[5]:.4f}f,
    .min_hurdle = 1.35f,
    .max_hurdle = 1.60f
}};

#ifdef __cplusplus
}}
#endif

#endif /* ML_SHAPING_MODEL_H */
"""
    os.makedirs(os.path.dirname(os.path.abspath(output_header)), exist_ok=True)
    with open(output_header, 'w') as f:
        f.write(header_content)
    print(f"Generated ML model header: {output_header}")


def main():
    parser = argparse.ArgumentParser(description="FAAC ML Shaping Model Trainer")
    parser.add_argument("dataset", help="Input dataset JSON path")
    parser.add_argument("--output", "-o", default="libfaac/ml_shaping_model.h", help="Output C header path")
    args = parser.parse_args()

    train_model(args.dataset, args.output)


if __name__ == "__main__":
    main()

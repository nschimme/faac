void sbr_qmf_analysis_init(sbr_qmf_analysis_t *qmf)
{
    memset(qmf, 0, sizeof(sbr_qmf_analysis_t));

    if (!qmf_lut_init) {
        int k, n;
        for (k = 0; k < 64; k++) {
            faac_real phase_base = (faac_real)M_PI / 64.0f * (k + 0.5f);
            for (n = 0; n < 640; n++) {
                faac_real phase = phase_base * (n - 32);
                qmf_cos_lut[k][n] = (faac_real)cos(phase);
                qmf_sin_lut[k][n] = (faac_real)sin(phase);
            }
        }
        qmf_lut_init = 1;
    }
}

/* 64-band Complex Polyphase Filterbank Analysis */
void sbr_qmf_analysis(sbr_qmf_analysis_t *qmf, const faac_real *input, faac_real X[32][64][2])
{
    int i, k, n, l;
    faac_real u[640];

    for (l = 0; l < 32; l++) {
        /* Shift samples and add new ones */
        for (i = 639; i >= 64; i--) {
            qmf->x[i] = qmf->x[i - 64];
        }
        for (i = 0; i < 64; i++) {
            qmf->x[63 - i] = input[l * 64 + i];
        }

        /* Windowing */
        for (n = 0; n < 640; n++) {
            u[n] = qmf->x[n] * qmf_window[n];
        }

        /* Matrix modulation: X[k][l] = Sum(u[n] * exp(i * (pi/64) * (k+0.5) * (n-32))) */
        for (k = 0; k < 64; k++) {
            faac_real re = 0;
            faac_real im = 0;
            const faac_real *c_lut = qmf_cos_lut[k];
            const faac_real *s_lut = qmf_sin_lut[k];

            for (n = 0; n < 640; n++) {
                re += u[n] * c_lut[n];
                im += u[n] * s_lut[n];
            }
            X[l][k][0] = re;
            X[l][k][1] = im;
        }
    }
}
